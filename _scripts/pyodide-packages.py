"""Write _scripts/pyodide-packages.nix: the Pyodide wheels the site hosts itself.

WANT lists the packages posts may load in PyScript; their dependencies are added from
Pyodide's lock file (the one in the flake's PyScript bundle), with the lock's sha256 for
each wheel, so the flake fetches exactly the files Pyodide expects.

Run from the repo root inside the dev shell after changing WANT or the PyScript bundle:
    python _scripts/pyodide-packages.py
"""
import json
import os
from pathlib import Path

# The Pyodide release the PyScript bundle ships (its release notes; the lock file has no
# version). A wrong value fails the flake build: every wheel is checked against its sha256.
PYODIDE = "314.0.3"

WANT = ["numpy", "scipy", "matplotlib", "sympy", "pandas", "scikit-learn", "micropip"]

lock = json.loads((Path(os.environ["PYSCRIPT_DIR"]) / "pyodide" / "pyodide-lock.json").read_text())
pkgs = lock["packages"]
by_lower = {name.lower(): name for name in pkgs}

todo = [by_lower[w.lower()] for w in WANT]
seen: set[str] = set()
while todo:
    name = todo.pop()
    if name in seen:
        continue
    seen.add(name)
    todo += [by_lower[d.lower()] for d in pkgs[name]["depends"]]

lines = [
    "# Generated by _scripts/pyodide-packages.py from Pyodide's lock file; don't edit by hand.",
    f"# Wanted: {', '.join(WANT)} (plus dependencies).",
    "{",
    f'  version = "{PYODIDE}";',
    "  wheels = [",
]
for name in sorted(seen, key=str.lower):
    p = pkgs[name]
    lines.append(f'    {{ file = "{p["file_name"]}"; sha256 = "{p["sha256"]}"; }}  # {name}')
lines += ["  ];", "}", ""]
Path("_scripts/pyodide-packages.nix").write_text("\n".join(lines))
print(f"{len(seen)} wheels for Pyodide {PYODIDE}")
